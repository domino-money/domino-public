#!/usr/bin/env python3
"""Export disabled onboarding-v1 schemas, types and synthetic producer fixtures."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT / 'backend/tests')]
from onboarding_models import CONTRACT_VERSION, ERROR_STATUS_BY_CODE, REQUEST_MODELS, RESPONSE_MODELS
from onboarding_contract_fixtures import build_fixtures, build_variants

DEST = ROOT / 'api-contracts/onboarding-v1'


def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def name(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def types(schemas):
    definitions = {}
    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        if 'anyOf' in schema:
            return ' | '.join(render(value) for value in schema['anyOf'])
        if schema.get('type') == 'object':
            required = schema.get('required', [])
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                for key, value in schema['properties'].items()) + '\n}'
        if schema.get('type') == 'array':
            return 'Array<' + render(schema['items']) + '>'
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]
    roots = []
    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_onboarding_type')
                definitions[key] = value
            roots.append(f'export type {name(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-onboarding-contract.py. Preview only; no spending authority.',
             f'export type OnboardingContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ['Request', 'Response']:
        lines.append('export interface Onboarding' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {name(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.append('export type OnboardingRoute = keyof OnboardingRequests;')
    lines.append('export type OnboardingErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE)) + ';')
    lines.append('export type OnboardingError = {error: OnboardingErrorCode};')
    return '\n\n'.join(lines) + '\n'


def build():
    files, schemas = {}, {}
    for route in sorted(REQUEST_MODELS):
        schemas[route] = {}
        for kind, models in [('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)]:
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                           '$id': f'https://domino.invalid/contracts/onboarding-v1/{route}.{kind}.schema.json',
                           'x-contract-version': CONTRACT_VERSION,
                           'x-domino-constraints': [
                               'All scalars are strict; JSON number lexemes must be canonical safe integers.',
                               'Raw token strings are exact canonical uint256 values (positive when specified).',
                               'Pool keys are ordered, distinct, hookless and fixed fee; the backend verifies Keccak PoolId.',
                               'Selected ticks must be spaced and ordered; the independent token must belong to the pool.',
                               'Preview timestamps have a 30-second lifetime; position prepared deadline is 1200 seconds.',
                               'Unknown values remain null; cost/status arithmetic must match the adapter projection.',
                               'Session-derived owner, response identity and freshness are checked by the service.']})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    requests, responses, errors = build_fixtures()
    for kind, values in [('requests', requests), ('responses', responses)]:
        for route, body in values.items():
            files[f'fixtures/{kind}/{route}.json'] = text(body)
    for name_, (_, body) in build_variants().items():
        files[f'fixtures/variants/{name_}.json'] = text(body)
    files['fixtures/errors.json'] = text(errors)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object',
        'required': ['error'], 'additionalProperties': False,
        'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE,
    })
    files['schema-data.mjs'] = '// Generated by scripts/export-onboarding-contract.py.\nexport const SCHEMAS = ' + text(schemas).rstrip() + ';\nexport const ERRORS = ' + text(ERROR_STATUS_BY_CODE).rstrip() + ';\n'
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = '''// Generated by scripts/export-onboarding-contract.py.
import type {OnboardingRoute, OnboardingRequests, OnboardingResponses, OnboardingError, OnboardingErrorCode} from './types.js';
export const CONTRACT_VERSION: '1.0.0';
export const ROUTES: readonly OnboardingRoute[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<OnboardingErrorCode, number>>;
export function validateRequest<R extends OnboardingRoute>(route:R, value:unknown):value is OnboardingRequests[R];
export function validateResponse<R extends OnboardingRoute>(route:R, value:unknown):value is OnboardingResponses[R];
export function validateError(status:number, value:unknown):value is OnboardingError;
'''
    source_paths = ['backend/onboarding_models.py', 'backend/onboarding_api.py', 'backend/authenticated_api.py', 'backend/access_transport.py',
                    'backend/onboarding_service.py', 'backend/onboarding_auth.py',
                    'backend/session_store.py', 'backend/hop_log.py', 'backend/session_models.py',
                    'backend/tests/test_onboarding_flow.py', 'backend/tests/test_onboarding_auth.py', 'backend/tests/onboarding_contract_fixtures.py',
                    'backend/uniswap_quote.py', 'backend/uniswap_position.py',
                    'backend/tests/test_uniswap_quote.py', 'backend/tests/test_uniswap_position.py',
                    'backend/tests/test_lp_mint_inspection.py', 'scripts/export-onboarding-contract.py']
    manifest = {
        'contract': 'onboarding-v1', 'contractVersion': CONTRACT_VERSION,
        'status': 'candidate_disabled_pending_consumer_acknowledgement',
        'generator': 'scripts/export-onboarding-contract.py',
        'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()}
                    for path in source_paths],
        'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()} for path, value in sorted(files.items())],
    }
    for path in ['runtime.mjs', 'README.md', 'consumer.typecheck.mts']:
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST / path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name_, value in build().items():
        path = DEST / name_
        if args.check:
            if not path.is_file() or path.read_text() != value:
                drift.append(name_)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    if drift:
        print('Onboarding contract drift: ' + ', '.join(drift))
        return 1
    print('Onboarding contract checked.' if args.check else 'Onboarding contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
