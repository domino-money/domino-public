def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    files = build_files()
    changed = [name for name, value in files.items() if not (DEST / name).is_file() or
               (DEST / name).read_bytes() != value.encode('utf-8')]
    previous = json.loads((DEST / 'manifest.json').read_bytes()) if (DEST / 'manifest.json').exists() else {'files': []}
    obsolete = [entry['path'] for entry in previous['files'] if entry['path'] not in files]
    if args.check:
        if changed or obsolete:
            print('Read-v2 contract drift: ' + ', '.join(sorted(changed + obsolete)))
            return 1
        print(f'Read-v2 contract {contract.CONTRACT_VERSION}: {len(files)} files match byte-for-byte.')
        return 0
    for name, value in files.items():
        path = DEST / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(value.encode('utf-8'))
    for name in obsolete:
        path = (DEST / name).resolve()
        if path.is_relative_to(DEST.resolve()):
            path.unlink(missing_ok=True)
    print(f'Generated read-v2 contract {contract.CONTRACT_VERSION}: {len(files)} files.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
