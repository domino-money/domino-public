#!/usr/bin/env python3
"""Export the private, read-only durable execution status contract."""
import argparse, hashlib, json, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
from execution_status import CONTRACT_VERSION, REQUEST_MODELS, RESPONSE_MODELS, ERROR_STATUS_BY_CODE
DEST=ROOT/'api-contracts/execution-v1'
SOURCES=['backend/automation_tariff.py','backend/execution_status.py', 'backend/access_transport.py','backend/execution_status_runtime.py', 'backend/authenticated_api.py', 'backend/hop_log.py', 'backend/onboarding_auth.py','backend/migrations/019_execution_journal.sql','bridge/src/execution-worker.mjs','scripts/export-execution-contract.py']
def text(value):return json.dumps(value,indent=2,sort_keys=True)+'\n'
def typename(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def types(schemas):
    definitions, roots = {}, []

    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            # Array constants are exact TS tuples, not an unconstrained array.
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        for keyword in ('oneOf', 'anyOf'):
            if keyword in schema:
                return ' | '.join(render(value) for value in schema[keyword])
        if schema.get('type') == 'object':
            required = schema.get('required', [])
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                for key, value in schema['properties'].items()) + '\n}'
        if schema.get('type') == 'array':
            return 'Array<' + render(schema['items']) + '>'
        if schema.get('type') == 'integer' and schema.get('minimum') == schema.get('maximum') and 'minimum' in schema:
            return str(schema['minimum'])
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]

    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_execution_type')
                definitions[key] = value
            roots.append(f'export type {typename(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-execution-v2-contract.py. Private managed evidence; no execution.',
             f'export type ExecutionContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ('Request', 'Response'):
        lines.append('export interface Execution' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {typename(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.extend(['export type ExecutionRoute = keyof ExecutionRequests;',
        'export type ExecutionErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE)) + ';',
        'export type ExecutionError = {error: ExecutionErrorCode};'])
    return '\n\n'.join(lines) + '\n'


def build():
    schemas={route:{kind:models[route].model_json_schema() for kind,models in [('request',REQUEST_MODELS),('response',RESPONSE_MODELS)]} for route in sorted(REQUEST_MODELS)}
    files={f'schemas/{route}.{kind}.schema.json':text(schema) for route,kinds in schemas.items() for kind,schema in kinds.items()}
    files['schema-data.mjs']='// Generated.\nexport const SCHEMAS = '+text(schemas).strip()+';\nexport const ERRORS = '+text(ERROR_STATUS_BY_CODE).strip()+';\n'
    files['types.ts']=types(schemas)
    files['runtime.d.mts']="""import type {ExecutionRoute,ExecutionRequests,ExecutionResponses,ExecutionError,ExecutionErrorCode} from './types.js';
export const CONTRACT_VERSION:'1.0.0-rc.1';
export const ROUTES:readonly ExecutionRoute[];
export const ERROR_STATUS_BY_CODE:Readonly<Record<ExecutionErrorCode,number>>;
export function validateRequest<R extends ExecutionRoute>(route:R,value:unknown):value is ExecutionRequests[R];
export function validateResponse<R extends ExecutionRoute>(route:R,value:unknown):value is ExecutionResponses[R];
export function validateError(status:number,value:unknown):value is ExecutionError;
"""
    fixture=json.loads((ROOT/'backend/tests/fixtures/execution/status-wire.json').read_text())
    files['fixtures/status-wire.json']=text(fixture)
    sources=SOURCES+['backend/tests/fixtures/execution/status-wire.json']
    manifest={'contract':'execution-v1','contractVersion':CONTRACT_VERSION,'status':'implemented_default_off','generator':'scripts/export-execution-contract.py',
      'sources':[{'path':p,'sha256':hashlib.sha256((ROOT/p).read_bytes()).hexdigest()} for p in sources],
      'files':[{'path':p,'sha256':hashlib.sha256(v.encode()).hexdigest()} for p,v in sorted(files.items())]}
    for p in ['runtime.mjs', '../shared/closed-schema.mjs','README.md','consumer.test.mjs']:manifest['files'].append({'path':p,'sha256':hashlib.sha256((DEST/p).read_bytes()).hexdigest()})
    files['manifest.json']=text(manifest)
    return files

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();drift=[]
    for name,value in build().items():
        path=DEST/name
        if args.check:
            if not path.is_file() or path.read_text()!=value:drift.append(name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value)
    if drift:print('Execution contract drift: '+', '.join(drift));return 1
    print('Execution contract checked.' if args.check else 'Execution contract exported.');return 0
if __name__=='__main__':raise SystemExit(main())
