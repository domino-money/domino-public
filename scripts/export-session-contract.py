#!/usr/bin/env python3
"""Export the disabled session-v1 models and deterministic fixtures; no network/DB."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT / 'backend/tests')]
from session_models import CONTRACT_VERSION, ERROR_STATUS_BY_CODE, REQUEST_MODELS, RESPONSE_MODELS
from session_contract_fixtures import build_fixtures

DEST = ROOT / 'api-contracts/session-v1'


def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def name(route, kind):
    return route.title() + kind.title()


def types(schemas):
    definitions = {}
    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        if schema.get('type') == 'object':
            if not schema['properties']:
                return 'Record<string, never>'
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ': ' + render(value) + ';'
                                    for key, value in schema['properties'].items()) + '\n}'
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]
    roots = []
    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_session_type')
                definitions[key] = value
            roots.append(f'export type {name(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-session-contract.py. Login only; no spending authority.',
             f'export type SessionContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ['Request', 'Response']:
        lines.append('export interface Session' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {name(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.append('export type SessionRoute = keyof SessionRequests;')
    lines.append('export type SessionErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE)) + ';')
    lines.append('export type SessionError = {error: SessionErrorCode};')
    return '\n\n'.join(lines) + '\n'


def build():
    files, schemas = {}, {}
    for route in sorted(REQUEST_MODELS):
        schemas[route] = {}
        for kind, models in [('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)]:
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                           '$id': f'https://domino.invalid/contracts/session-v1/{route}.{kind}.schema.json',
                           'x-contract-version': CONTRACT_VERSION,
                           'x-domino-constraints': ['All timestamps are valid UTC calendar dates.',
                              'Messages must be well-formed UTF-8 and at most 2048 bytes.',
                              'Chain ID is the exact integer 4663 (no exponent/fraction/string/coercion).',
                              'Schema scalars are strict, including literal booleans.']})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    requests, responses, errors = build_fixtures()
    for route, body in requests.items():
        files[f'fixtures/requests/{route}.json'] = text(body)
    for route, body in responses.items():
        files[f'fixtures/responses/{route}.json'] = text(body)
    files['fixtures/errors.json'] = text(errors)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object',
        'required': ['error'], 'additionalProperties': False,
        'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE,
    })
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = '''// Generated by scripts/export-session-contract.py.
import type {SessionRoute, SessionRequests, SessionResponses, SessionError, SessionErrorCode} from './types.js';
export const CONTRACT_VERSION: '__VERSION__';
export const ROUTES: readonly SessionRoute[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<SessionErrorCode, number>>;
export function validateRequest<R extends SessionRoute>(route:R, value:unknown):value is SessionRequests[R];
export function validateResponse<R extends SessionRoute>(route:R, value:unknown):value is SessionResponses[R];
export function validateError(status:number, value:unknown):value is SessionError;
export function keys(value:unknown, names:readonly string[]):boolean;
export function credential(value:unknown):value is string;
export function validateEnvelope(route:SessionRoute, value:unknown):boolean;
'''.replace('__VERSION__', CONTRACT_VERSION)
    source_paths = ['backend/session_models.py', 'backend/session_api.py', 'backend/access_transport.py', 'backend/session_siwe.py', 'backend/session_service.py',
                    'backend/session_store.py', 'backend/hop_log.py', 'backend/wallet_access.py',
                    'backend/migrations/011_wallet_access.sql',
                    'backend/tests/session_contract_fixtures.py', 'scripts/export-session-contract.py']
    manifest = {
        'contract': 'session-v1', 'contractVersion': CONTRACT_VERSION,
        'status': 'candidate_disabled_pending_consumer_acknowledgement',
        'generator': 'scripts/export-session-contract.py',
        'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()}
                    for path in source_paths],
        'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()} for path, value in sorted(files.items())],
    }
    for path in ['runtime.mjs', 'README.md']:
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST / path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name_, value in build().items():
        path = DEST / name_
        if args.check:
            if not path.is_file() or path.read_text() != value:
                drift.append(name_)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    if drift:
        print('Session contract drift: ' + ', '.join(drift))
        return 1
    print('Session contract checked.' if args.check else 'Session contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
