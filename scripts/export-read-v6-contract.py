#!/usr/bin/env python3
"""Export read-v6 (Domino V2 wallet reads): schemas, types, producer fixtures and the manifest.

The schemas and types are generated from backend/v2_read_contract.py; the
fixtures are answers the producer builds (backend/tests/read_v6_contract_fixtures.py)
and answers with one defect each. runtime.mjs, the README and the consumer
test are written by hand and hashed into the manifest. `--check` compares
instead of writing.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT / 'backend/tests')]
from read_contract import ERROR_STATUS_BY_CODE  # noqa: E402
from v2_read_contract import (BALANCE_CHAIN_IDS, BLOCKERS, CHAIN_IDS, CHAIN_REASONS,  # noqa: E402
                              CONTRACT_VERSION, DISARM_REASONS, HEAD_MAX_AGE_SECONDS, LIMITATIONS, MAX_LAG_SECONDS,
                              REQUEST_MODELS, RESPONSE_MODELS, ROUTES, STALE_SECONDS, V2_ERRORS, WAITING_STALE_SECONDS,
                              WAITING_STATUSES, LIVE_FRESH_SECONDS, LIVE_LIMITATIONS, TOKEN_SOURCES, PRICE_FLOOR_USD,
                              PRICE_PROFILES)
import read_v6_contract_fixtures as fixtures  # noqa: E402

DEST = ROOT / 'api-contracts/read-v6'
SOURCES = ['backend/v2_read_contract.py', 'backend/v2_read_service.py', 'backend/v2_index_store.py',
           'backend/v2_chain_reads.py', 'backend/data/token-lists/uniswap-default.json',
           'backend/v2_waiting.py', 'backend/v2_activity.py', 'backend/v2_events.py', 'backend/read_contract.py', 'backend/read_api.py',
           'backend/read_gateway.py', 'backend/bridge_http.py', 'backend/migrations/052_v2_index.sql',
           'backend/tests/read_v6_contract_fixtures.py', 'backend/tests/v2_index_fixtures.py',
           'scripts/export-read-v6-contract.py']
HANDWRITTEN = ['runtime.mjs', '../shared/closed-schema.mjs', 'README.md', 'consumer.test.mjs']


def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + '\n'


def typename(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def render(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    for keyword in ('oneOf', 'anyOf'):
        if keyword in schema:
            return ' | '.join(render(value) for value in schema[keyword])
    if schema.get('type') == 'object':
        required = schema.get('required', [])
        return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                                 for key, value in schema['properties'].items()) + '\n}'
    if schema.get('type') == 'array':
        return 'Array<' + render(schema['items']) + '>'
    return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]


def types(schemas):
    definitions, roots = {}, []
    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_read_v6_type')
                definitions[key] = value
            roots.append(f'export type {typename(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-read-v6-contract.py. Raw integer strings, no USD, no signing.',
             f'export type ReadV6ContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ('Request', 'Response'):
        lines.append('export interface ReadV6' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {typename(route, kind)};' for route in ROUTES) + '\n}')
    lines.extend(['export type ReadV6Route = keyof ReadV6Requests;',
                  'export type ReadV6ErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE))
                  + ';', 'export type ReadV6Error = {error: ReadV6ErrorCode};'])
    return '\n\n'.join(lines) + '\n'


def constants():
    """What runtime.mjs needs to re-check an answer: the chains (and the ones chain-balances reads when asked), the
    limitations and the thresholds."""
    return {'chainIds': list(CHAIN_IDS), 'balanceChainIds': list(BALANCE_CHAIN_IDS),
            'limitations': list(LIMITATIONS), 'chainReasons': list(CHAIN_REASONS),
            'disarmReasons': [DISARM_REASONS[key] for key in sorted(DISARM_REASONS)], 'blockers': list(BLOCKERS),
            'headMaxAgeSeconds': HEAD_MAX_AGE_SECONDS, 'maxLagSeconds': MAX_LAG_SECONDS,
            'staleSeconds': STALE_SECONDS, 'tariffRates': {'assisted_swap': [65], 'automation': [200, 400],
                                                          'auto_exit': [20]},
            'waitingStatuses': list(WAITING_STATUSES), 'waitingStaleSeconds': WAITING_STALE_SECONDS,
            'v2Errors': list(V2_ERRORS), 'liveLimitations': list(LIVE_LIMITATIONS),
            'liveFreshSeconds': LIVE_FRESH_SECONDS, 'tokenSources': list(TOKEN_SOURCES),
            'priceFloorUsd': PRICE_FLOOR_USD,
            'priceProfiles': {str(chain_id): profile for chain_id, profile in PRICE_PROFILES.items()}}


def build():
    schemas, files = {}, {}
    for route in ROUTES:
        schemas[route] = {}
        for kind, models in (('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)):
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                           '$id': f'https://domino.invalid/contracts/read-v6/{route}.{kind}.schema.json',
                           'x-contract-version': CONTRACT_VERSION})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object', 'required': ['error'],
        'additionalProperties': False, 'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE})
    for route, body in fixtures.REQUESTS.items():
        files[f'fixtures/requests/{route}.json'] = text(body)
    for name, body in fixtures.valid().items():
        files[f'fixtures/valid/{name}.json'] = text(body)
    for name, (_route, body) in fixtures.invalid().items():
        files[f'fixtures/invalid/{name}.json'] = text(body)
    files['fixtures/errors.json'] = text(fixtures.errors())
    files['schema-data.mjs'] = ('// Generated by scripts/export-read-v6-contract.py.\nexport const SCHEMAS = '
                                + text(schemas).rstrip() + ';\nexport const ERRORS = '
                                + text(ERROR_STATUS_BY_CODE).rstrip() + ';\nexport const CONSTANTS = '
                                + text(constants()).rstrip() + ';\n')
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = '''// Generated by scripts/export-read-v6-contract.py.
import type {ReadV6Route, ReadV6Requests, ReadV6Responses, ReadV6Error, ReadV6ErrorCode} from './types.js';
export const CONTRACT_VERSION: '%s';
export const ROUTES: readonly ReadV6Route[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<ReadV6ErrorCode, number>>;
export function validateRequest<R extends ReadV6Route>(route:R, value:unknown):value is ReadV6Requests[R];
export function validateResponse<R extends ReadV6Route>(route:R, value:unknown):value is ReadV6Responses[R];
export function validateError(status:number, value:unknown):value is ReadV6Error;
/** The answer is about the wallet asked for, and a page is no longer than asked. */
export function validateExchange<R extends ReadV6Route>(route:R, request:unknown, response:unknown):boolean;
''' % CONTRACT_VERSION
    manifest = {'contract': 'read-v6', 'contractVersion': CONTRACT_VERSION,
                'status': 'candidate_disabled_pending_bridge_and_deployment',
                'generator': 'scripts/export-read-v6-contract.py',
                'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()}
                            for path in SOURCES],
                'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()}
                          for path, value in sorted(files.items())]}
    for path in HANDWRITTEN:
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST / path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    fixtures.check()
    expected = build()
    present = {path.relative_to(DEST).as_posix() for path in DEST.glob('fixtures/**/*.json')}
    extra = sorted(present - set(expected))
    if args.check:
        drift = sorted(name for name, value in expected.items()
                       if not (DEST / name).is_file() or (DEST / name).read_text() != value)
        if drift or extra:
            print('read-v6 contract drift: ' + ', '.join(drift + extra))
            return 1
        print('read-v6 contract checked.')
        return 0
    for name in extra:
        (DEST / name).unlink()
    for name, value in expected.items():
        path = DEST / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value)
    print('read-v6 contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
