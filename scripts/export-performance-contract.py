def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def typename(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def types(schemas):
    definitions, roots = {}, []

    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            # Array constants are exact TS tuples, not an unconstrained array.
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        for keyword in ('oneOf', 'anyOf'):
            if keyword in schema:
                return ' | '.join(render(value) for value in schema[keyword])
        if schema.get('type') == 'object':
            required = schema.get('required', [])
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                for key, value in schema['properties'].items()) + '\n}'
        if schema.get('type') == 'array':
            return 'Array<' + render(schema['items']) + '>'
        if schema.get('type') == 'integer' and schema.get('minimum') == schema.get('maximum') and 'minimum' in schema:
            return str(schema['minimum'])
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]

    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_performance_type')
                definitions[key] = value
            roots.append(f'export type {typename(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-performance-contract.py. Private, disabled; no financial results.',
             f'export type PerformanceContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ('Request', 'Response'):
        lines.append('export interface Performance' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {typename(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.extend(['export type PerformanceRoute = keyof PerformanceRequests;',
        'export type PerformanceErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE)) + ';',
        'export type PerformanceError = {error: PerformanceErrorCode};'])
    return '\n\n'.join(lines) + '\n'


def build():
    files, schemas = {}, {}
    for route in sorted(REQUEST_MODELS):
        schemas[route] = {}
        for kind, models in [('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)]:
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                '$id': f'https://domino.invalid/contracts/performance-v1/{route}.{kind}.schema.json',
                'x-contract-version': CONTRACT_VERSION, 'x-domino-constraints': [
                    'Strict safe JSON integers; nonzero canonical lowercase identities; unique requested/result epochs.',
                    'The request contains 1..8 epochIds only. Owner comes from the authenticated session.',
                    'Financial USD/APR/APY fields are required nulls; execution and complete24h are always false.',
                    'Collection spans are snapshot.timestamp minus baseline.timestamp, not fee/capital coverage.',
                    'Same block number means same hash; snapshots cannot precede baseline.',
                    'Collection reason, status and 120-second age boundary must agree.',
                    'Pages zero implies receipts/events zero; receipts zero implies events zero.',
                    'The runtime also enforces cross-field semantics and x-maximum-raw, beyond generic schema checks.',
                    'Owner/epoch request binding and session reauthorization remain server/consumer integration checks.']})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    requests, responses, errors = build_fixtures()
    for kind, values in [('requests', requests), ('responses', responses)]:
        for route, body in values.items():
            files[f'fixtures/{kind}/{route}.json'] = text(body)
    for name, body in build_variants().items():
        files[f'fixtures/variants/{name}.json'] = text(body)
    files['fixtures/errors.json'] = text(errors)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object',
        'required': ['error'], 'additionalProperties': False,
        'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE})
    files['schema-data.mjs'] = ('// Generated by scripts/export-performance-contract.py.\nexport const SCHEMAS = '
        + text(schemas).rstrip() + ';\nexport const ERRORS = ' + text(ERROR_STATUS_BY_CODE).rstrip() + ';\n')
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = f'''// Generated by scripts/export-performance-contract.py.
import type {{PerformanceRoute, PerformanceRequests, PerformanceResponses, PerformanceError, PerformanceErrorCode}} from './types.js';
export const CONTRACT_VERSION: '{CONTRACT_VERSION}';
export const ROUTES: readonly PerformanceRoute[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<PerformanceErrorCode, number>>;
export function validateRequest<R extends PerformanceRoute>(route:R, value:unknown):value is PerformanceRequests[R];
export function validateResponse<R extends PerformanceRoute>(route:R, value:unknown):value is PerformanceResponses[R];
export function validateError(status:number, value:unknown):value is PerformanceError;
'''
    manifest = {'contract': 'performance-v1', 'contractVersion': CONTRACT_VERSION,
        'status': 'candidate_disabled_pending_consumer_acknowledgement',
        'generator': 'scripts/export-performance-contract.py',
        'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT/path).read_bytes()).hexdigest()} for path in SOURCES],
        'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()} for path, value in sorted(files.items())]}
    for path in ('runtime.mjs', 'README.md', 'consumer.typecheck.mts'):
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST/path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name, value in build().items():
        path = DEST/name
        if args.check:
            if not path.is_file() or path.read_text() != value:
                drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    if drift:
        print('Performance contract drift: ' + ', '.join(drift))
        return 1
    print('Performance contract checked.' if args.check else 'Performance contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
