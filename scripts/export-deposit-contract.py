#!/usr/bin/env python3
"""Export disabled deposit-v1 schemas, types and synthetic producer fixtures."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT / 'backend/tests')]
from deposit_models import CONTRACT_VERSION, ERROR_STATUS_BY_CODE, REQUEST_MODELS, RESPONSE_MODELS
from deposit_contract_fixtures import build_fixtures, build_variants

DEST = ROOT / 'api-contracts/deposit-v1'


def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def name(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def types(schemas):
    definitions = {}
    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        if 'anyOf' in schema:
            return ' | '.join(render(value) for value in schema['anyOf'])
        if schema.get('type') == 'object':
            required = schema.get('required', [])
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                for key, value in schema['properties'].items()) + '\n}'
        if schema.get('type') == 'array':
            return 'Array<' + render(schema['items']) + '>'
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]
    roots = []
    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_deposit_type')
                definitions[key] = value
            roots.append(f'export type {name(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-deposit-contract.py. Wallet-signed deposits; no server broadcast.',
             f'export type DepositContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ['Request', 'Response']:
        lines.append('export interface Deposit' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {name(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.append('export type DepositRoute = keyof DepositRequests;')
    lines.append('export type DepositErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE)) + ';')
    lines.append('export type DepositError = {error: DepositErrorCode};')
    return '\n\n'.join(lines) + '\n'


def build():
    files, schemas = {}, {}
    for route in sorted(REQUEST_MODELS):
        schemas[route] = {}
        for kind, models in [('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)]:
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                           '$id': f'https://domino.invalid/contracts/deposit-v1/{route}.{kind}.schema.json',
                           'x-contract-version': CONTRACT_VERSION,
                           'x-domino-constraints': [
                               'Closed strict fields, exact raw integer strings, safe integer selectors.',
                               'SIWE-derived owner; no browser-selected recipient or provider.',
                               'Immutable pool/range/budget/gas selection and optimistic operation version.',
                               'Wallet payload only on prepare, tied to an already persisted owner nonce.',
                               'Narrow ABI calldata is re-encoded and compared; no arbitrary calls.',
                               'Pending versus finalized receipts and missing values remain explicit.']})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    requests, responses, errors = build_fixtures()
    for kind, values in [('requests', requests), ('responses', responses)]:
        for route, body in values.items():
            files[f'fixtures/{kind}/{route}.json'] = text(body)
    for name_, (_, body) in build_variants().items():
        files[f'fixtures/variants/{name_}.json'] = text(body)
    files['fixtures/errors.json'] = text(errors)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object',
        'required': ['error'], 'additionalProperties': False,
        'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE,
    })
    files['schema-data.mjs'] = '// Generated by scripts/export-deposit-contract.py.\nexport const SCHEMAS = ' + text(schemas).rstrip() + ';\nexport const ERRORS = ' + text(ERROR_STATUS_BY_CODE).rstrip() + ';\n'
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = f'''// Generated by scripts/export-deposit-contract.py.
import type {{DepositRoute, DepositRequests, DepositResponses, DepositError, DepositErrorCode, DepositSelection, PreparedArtifact}} from './types.js';
export const CONTRACT_VERSION: '{CONTRACT_VERSION}';
export const ROUTES: readonly DepositRoute[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<DepositErrorCode, number>>;
export function validateRequest<R extends DepositRoute>(route:R, value:unknown):value is DepositRequests[R];
export function validateResponse<R extends DepositRoute>(route:R, value:unknown):value is DepositResponses[R];
export function validateError(status:number, value:unknown):value is DepositError;
export function validateWalletStep(selection:DepositSelection, owner:string, artifact:PreparedArtifact):boolean;
'''
    source_paths = ['backend/deposit_models.py', 'backend/deposit_service.py', 'backend/deposit_allowances.py',
                    'backend/deposit_prepare.py', 'backend/deposit_receipt.py', 'backend/deposit_store.py',
                    'backend/migrations/014_deposit_draft_recovery.sql',
                    'backend/tests/test_deposit_capacity_recovery.py',
                    'backend/tests/test_deposit_replacement_recovery.py',
                    'backend/tests/deposit_contract_fixtures.py', 'backend/tests/test_deposit_receipt.py',
                    'backend/tests/test_lp_mint_inspection.py', 'scripts/export-deposit-contract.py']
    manifest = {
        'contract': 'deposit-v1', 'contractVersion': CONTRACT_VERSION,
        'status': 'candidate_disabled_pending_consumer_acknowledgement',
        'generator': 'scripts/export-deposit-contract.py',
        'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()}
                    for path in source_paths],
        'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()} for path, value in sorted(files.items())],
    }
    for path in ['runtime.mjs', 'README.md', 'consumer.typecheck.mts']:
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST / path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name_, value in build().items():
        path = DEST / name_
        if args.check:
            if not path.is_file() or path.read_text() != value:
                drift.append(name_)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    if drift:
        print('Deposit contract drift: ' + ', '.join(drift))
        return 1
    print('Deposit contract checked.' if args.check else 'Deposit contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
