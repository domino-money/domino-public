def json_text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False)+'\n'


def type_name(name):
    return ''.join(part.title() for part in name.replace('.', '-').split('-'))


def typescript(schemas):
    declarations = {}
    roots = []
    def type_for(schema):
        if '$ref' in schema: return schema['$ref'].rsplit('/', 1)[1]
        if 'const' in schema: return json.dumps(schema['const'])
        if 'enum' in schema: return ' | '.join(json.dumps(value) for value in schema['enum'])
        for key in ('oneOf', 'anyOf'):
            if key in schema: return '('+' | '.join(type_for(item) for item in schema[key])+')'
        kind = schema.get('type')
        if kind == 'null': return 'null'
        if kind == 'string': return 'string'
        if kind in ('integer', 'number'): return 'number'
        if kind == 'boolean': return 'boolean'
        if kind == 'array': return 'Array<'+type_for(schema['items'])+'>'
        if kind == 'object':
            required = schema.get('required', [])
            fields = [f'  {json.dumps(name)}'+('' if name in required else '?')+': '+type_for(value)+';'
                      for name, value in schema['properties'].items()]
            return '{\n'+'\n'.join(fields)+'\n}'
        raise ValueError('unsupported_type_schema')
    for filename, schema in schemas.items():
        for name, definition in schema.get('$defs', {}).items():
            rendered = type_for(definition)
            if name in declarations and declarations[name] != rendered:
                raise ValueError('conflicting_type_definition:'+name)
            declarations[name] = rendered
        roots.append((type_name(filename.removesuffix('.schema.json')), type_for(schema)))
    lines = ['// Generated by scripts/export-read-contract.py. Do not edit.',
             '// Numeric quantities are exact strings. Metadata strings are untrusted text.',
             f'export type ReadContractVersion = "{CONTRACT_VERSION}";']
    for name, rendered in sorted(declarations.items()): lines.append(f'export type {name} = {rendered};')
    for name, rendered in roots: lines.append(f'export type {name} = {rendered};')
    lines.append('export interface ReadResponses {')
    for route in ENABLED_READS: lines.append(f'  "{route}": {type_name(route)}Response;')
    lines += ['  "capabilities": CapabilitiesResponse;', '}',
              'export interface ReadRequests {']
    for route in ENABLED_READS: lines.append(f'  "{route}": {type_name(route)}Request;')
    lines += ['}', 'export type ReadRoute = keyof ReadRequests;']
    return '\n\n'.join(lines)+'\n'


RUNTIME = r'''
// Generated by scripts/export-read-contract.py. Do not edit.
// This deliberately implements only the closed JSON Schema vocabulary emitted
// by that generator. Unsupported assertions fail closed; no coercion, stripping,
// defaults, HTML rendering, URL fetching or dependencies. JSON input only.
const ANNOTATIONS = new Set(['$schema', '$id', '$defs', 'title', 'description', 'default',
  'discriminator', 'x-contract-version', 'x-domino-constraints']);
const ASSERTIONS = new Set(['$ref', 'type', 'const', 'enum', 'anyOf', 'oneOf', 'allOf',
  'properties', 'required', 'additionalProperties', 'items', 'minItems', 'maxItems',
  'uniqueItems', 'pattern', 'minLength', 'maxLength', 'minimum', 'maximum']);
function check(value, schema, root, depth = 0) {
  if (depth > 96 || !schema || typeof schema !== 'object') return false;
  if (Object.keys(schema).some(key => !ANNOTATIONS.has(key) && !ASSERTIONS.has(key))) return false;
  if (schema.$ref) {
    if (!/^#\/\$defs\/[A-Za-z_][A-Za-z0-9_]*$/.test(schema.$ref)) return false;
    return check(value, root.$defs?.[schema.$ref.split('/').at(-1)], root, depth + 1);
  }
  if (Object.hasOwn(schema, 'const') && value !== schema.const) return false;
  if (schema.enum && !schema.enum.some(item => item === value)) return false;
  if (schema.anyOf && !schema.anyOf.some(item => check(value, item, root, depth + 1))) return false;
  if (schema.oneOf && schema.oneOf.filter(item => check(value, item, root, depth + 1)).length !== 1) return false;
  if (schema.allOf && !schema.allOf.every(item => check(value, item, root, depth + 1))) return false;
  switch (schema.type) {
    case 'null': if (value !== null) return false; break;
    case 'boolean': if (typeof value !== 'boolean') return false; break;
    case 'integer':
      if (!Number.isSafeInteger(value)) return false;
      if (schema.minimum !== undefined && value < schema.minimum) return false;
      if (schema.maximum !== undefined && value > schema.maximum) return false;
      break;
    case 'string': {
      if (typeof value !== 'string') return false;
      const length = [...value].length;
      if (schema.minLength !== undefined && length < schema.minLength) return false;
      if (schema.maxLength !== undefined && length > schema.maxLength) return false;
      // JS $ accepts a final newline; enforce full match for anchored patterns.
      if (schema.pattern) {
        const match = new RegExp(schema.pattern, 'u').exec(value);
        if (!match || (schema.pattern.startsWith('^') && schema.pattern.endsWith('$') && match[0] !== value)) return false;
      }
      break;
    }
    case 'array':
      if (!Array.isArray(value)) return false;
      if (schema.minItems !== undefined && value.length < schema.minItems) return false;
      if (schema.maxItems !== undefined && value.length > schema.maxItems) return false;
      if (schema.uniqueItems && new Set(value.map(item => JSON.stringify(item))).size !== value.length) return false;
      if (!value.every(item => check(item, schema.items, root, depth + 1))) return false;
      break;
    case 'object':
      if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
      if (Object.getPrototypeOf(value) !== Object.prototype && Object.getPrototypeOf(value) !== null) return false;
      if (!schema.required?.every(key => Object.hasOwn(value, key)) && schema.required?.length) return false;
      if (schema.additionalProperties !== false) return false;
      if (!Object.keys(value).every(key => Object.hasOwn(schema.properties, key))) return false;
      if (!Object.entries(value).every(([key, child]) => check(child, schema.properties[key], root, depth + 1))) return false;
      break;
    case undefined: break;
    default: return false;
  }
  return true;
}
export function validateResponse(route, payload) {
  if (typeof route !== 'string' || !Object.hasOwn(RESPONSE_SCHEMAS, route)) return false;
  const schema = RESPONSE_SCHEMAS[route];
  if (!schema || !check(payload, schema, schema)) return false;
  if (route === 'pool-metrics' && payload.usableAsCurrent24h && !(
    payload.valuation.status === 'qualified_historical_calculation' &&
    payload.valuation.complete24h && payload.valuation.feeAprPercent !== null &&
    payload.capital.status === 'reconciled_event_history' && payload.capital.complete24h &&
    payload.freshness.status === 'fresh')) return false;
  return route !== 'capabilities' || payload.dataMode !== 'disabled' || payload.enabledReads.length === 0;
}
export function assertResponse(route, payload) {
  if (!validateResponse(route, payload)) throw new TypeError('upstream_contract_mismatch');
  return payload;
}
export function validateError(status, payload) {
  return check(payload, ERROR_SCHEMA, ERROR_SCHEMA) && ERROR_STATUS_BY_CODE[payload.error] === status;
}
export function validateRequest(route, payload) {
  if (typeof route !== 'string' || !Object.hasOwn(REQUEST_SCHEMAS, route)) return false;
  const schema = REQUEST_SCHEMAS[route];
  if (!schema || !check(payload, schema, schema)) return false;
  if (route === 'pools' || route === 'catalogue') {
    if (payload.pairedToken != null && payload.pairedToken.toLowerCase() === payload.token.toLowerCase()) return false;
    if (route === 'pools' && (payload.poolIds?.length ?? 0) > (payload.maxPools ?? 12)) return false;
    if (route === 'catalogue' && payload.afterPoolId != null && payload.revision == null) return false;
  }
  if (route === 'nft-positions') {
    if (new Set(payload.tokenIds).size !== payload.tokenIds.length) return false;
    if (payload.tokenIds.some(value => BigInt(value) >= 2n**256n)) return false;
  }
  return true;
}
export function assertRequest(route, payload) {
  if (!validateRequest(route, payload)) throw new TypeError('invalid_request');
  return payload;
}
'''


def build_files():
    schemas = export_contract()
    for route, model in REQUEST_MODELS.items():
        schema = model.model_json_schema()
        schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                       '$id': f'https://domino.invalid/contracts/read-v1/{route}.request.schema.json',
                       'x-contract-version': CONTRACT_VERSION})
        if route == 'pools':
            schema['x-domino-constraints'] = ['pairedToken must differ from token case-insensitively',
                                               'poolIds length must not exceed maxPools (default 12)']
        if route == 'catalogue':
            schema['x-domino-constraints'] = ['pairedToken must differ from token case-insensitively',
                                              'revision required when afterPoolId is supplied']
        if route == 'nft-positions':
            schema['properties']['tokenIds']['uniqueItems'] = True
            schema['properties']['tokenIds']['items']['pattern'] = unsigned_string_pattern(2**256-1)
            schema['properties']['tokenIds']['items']['maxLength'] = 78
            schema['x-domino-constraints'] = ['tokenIds must be decimal integers less than 2**256']
        schemas[f'{route}.request.schema.json'] = schema
    files = {f'schemas/{name}': json_text(schema) for name, schema in sorted(schemas.items())}
    files['types.ts'] = typescript(schemas)
    response_schemas = {route: schemas[f'{route}.response.schema.json'] for route in (*ENABLED_READS, 'capabilities')}
    request_schemas = {route: schemas[f'{route}.request.schema.json'] for route in ENABLED_READS}
    prelude = [f'export const CONTRACT_VERSION = {json.dumps(CONTRACT_VERSION)};',
               f'export const ENABLED_READS = Object.freeze({json.dumps(list(ENABLED_READS))});',
               f'export const RESPONSE_SCHEMA_VERSIONS = Object.freeze({json.dumps({route: schemas[route+".response.schema.json"]["properties"]["schemaVersion"]["const"] for route in ENABLED_READS}, sort_keys=True)});',
               f'export const ERROR_STATUS_BY_CODE = Object.freeze({json.dumps(ERROR_STATUS_BY_CODE, sort_keys=True)});',
               'const RESPONSE_SCHEMAS = '+json.dumps(response_schemas, sort_keys=True, separators=(',', ':'))+';',
               'const REQUEST_SCHEMAS = '+json.dumps(request_schemas, sort_keys=True, separators=(',', ':'))+';',
               'const ERROR_SCHEMA = '+json.dumps(schemas['error.response.schema.json'], sort_keys=True, separators=(',', ':'))+';']
    files['runtime.mjs'] = '\n'.join(prelude)+'\n'+RUNTIME.lstrip()
    files['runtime.d.mts'] = '''// Generated by scripts/export-read-contract.py. Do not edit.
import type { ReadRequests, ReadResponses, ReadContractVersion, ErrorResponse } from './types.js';
export const CONTRACT_VERSION: ReadContractVersion;
export const ENABLED_READS: readonly (keyof ReadRequests)[];
export const RESPONSE_SCHEMA_VERSIONS: Readonly<Record<keyof ReadRequests, 1 | 2>>;
export const ERROR_STATUS_BY_CODE: Readonly<Record<ErrorResponse['error'], number>>;
export function validateResponse<R extends keyof ReadResponses>(route: R, payload: unknown): payload is ReadResponses[R];
export function assertResponse<R extends keyof ReadResponses>(route: R, payload: unknown): ReadResponses[R];
export function validateRequest<R extends keyof ReadRequests>(route: R, payload: unknown): payload is ReadRequests[R];
export function assertRequest<R extends keyof ReadRequests>(route: R, payload: unknown): ReadRequests[R];
export function validateError(status: number, payload: unknown): payload is ErrorResponse;
'''
    for name, fixture in build_fixtures().items(): files[name] = json_text(fixture)
    files['fixtures/request-boundaries.json'] = json_text(request_boundaries())
    for name in ('README.md', 'consumer.test.mjs', 'consumer.typecheck.mts', 'progressive.mjs', 'progressive.d.mts', 'progressive.test.mjs'):
        files[name] = (DESTINATION/name).read_text()
    manifest = {'contractVersion': CONTRACT_VERSION, 'producerApplicationVersion': '0.8.0',
                'status': 'candidate_disabled_pending_consumer_acknowledgement',
                'generator': 'scripts/export-read-contract.py',
                'sources': [{'path': name, 'sha256': hashlib.sha256((ROOT/name).read_bytes()).hexdigest()}
                            for name in ('backend/read_contract.py', 'backend/read_api.py', 'backend/read_service.py',
                                         'backend/rpc_failover.py', 'backend/rpc_config.py', 'backend/local_config.py',
                                         'backend/historical_read.py', 'backend/historical_capacity.py', 'bridge/src/request-contract.mjs',
                                         'backend/read_gateway.py', 'backend/bridge_state.py', 'backend/bridge_http.py',
                                         'backend/metrics_service.py', 'backend/activity_store.py', 'backend/position_store.py',
                                         'backend/fee_store.py', 'backend/capital_store.py', 'backend/price_history.py',
                                         'backend/valuation.py', 'backend/chainlink_reference.py', 'backend/discovery.py', 'backend/nft_ownership.py',
                                         'backend/inventory.py', 'backend/market_cache.py', 'backend/market_data.py',
                                         'backend/read_deadline.py', 'backend/catalogue.py', 'backend/position_accounting.py',
                                         'backend/fee_accounting.py', 'backend/pool_activity.py',
                                         'backend/tests/fixtures/position-reference.json',
                                         'backend/tests/read_history_fixtures.py', 'backend/tests/read_request_fixtures.py',
                                         'backend/tests/test_read_contract.py', 'backend/tests/test_read_reconciliation.py',
                                         'scripts/export-read-contract.py')],
                'enabledReadCandidates': list(ENABLED_READS),
                'browserTransformations': [{'path': 'inventory.nextCursor', 'route': 'wallet-assets',
                                            'producerType': 'string|null', 'gatewayType': 'string|null',
                                            'change': 'internal cursor exchanged for opaque gateway handle'}],
                'files': [{'path': path, 'sha256': hashlib.sha256(content.encode()).hexdigest()}
                          for path, content in sorted(files.items())]}
    files['manifest.json'] = json_text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail without writing if generated files drift.')
    args = parser.parse_args()
    files = build_files()
    changed = [name for name, contents in files.items()
               if not (DESTINATION/name).is_file() or (DESTINATION/name).read_text() != contents]
    generated_paths = set(files)
    old_manifest = DESTINATION/'manifest.json'
    previous = json.loads(old_manifest.read_text()) if old_manifest.exists() else {'files': []}
    obsolete = [item['path'] for item in previous.get('files', []) if item['path'] not in generated_paths]
    if args.check:
        if changed or obsolete:
            print('Read contract drift: '+', '.join(sorted(changed+obsolete)))
            return 1
        print(f'Read contract {CONTRACT_VERSION}: {len(files)} generated files match.')
        return 0
    for name, contents in files.items():
        path = DESTINATION/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
    # Delete only paths previously recorded as generated, never collaborator files.
    for name in obsolete:
        path = (DESTINATION/name).resolve()
        if path.is_relative_to(DESTINATION.resolve()): path.unlink(missing_ok=True)
    print(f'Generated read contract {CONTRACT_VERSION}: {len(files)} files.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
