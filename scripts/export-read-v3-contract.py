def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = build_files()
    changed = [name for name, body in files.items() if not (DEST / name).exists() or (DEST / name).read_text() != body]
    if args.check:
        if changed:
            print('Read-v3 contract drift: ' + ', '.join(changed))
            return 1
        print(f'Read-v3 contract {contract.CONTRACT_VERSION}: {len(files)} files match byte-for-byte.')
        return 0
    for name, body in files.items():
        path = DEST / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    print(f'Generated read-v3 contract {contract.CONTRACT_VERSION}: {len(files)} files.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
