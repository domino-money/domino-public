#!/usr/bin/env python3
"""Export crosschain-v1 (deposit from another chain): schemas, types, pinned targets and producer fixtures."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT / 'backend/tests')]
from crosschain_models import (CONTRACT_VERSION, DESTINATIONS, ERROR_STATUS_BY_CODE, PINS, POLL_SECONDS,
                               QUOTE_LIFETIME_SECONDS, REQUEST_MODELS, RESPONSE_MODELS)
from crosschain_contract_fixtures import build_fixtures, build_variants

DEST = ROOT / 'api-contracts/crosschain-v1'
# crosschain_models_rc1.py: the frozen 1.0.0-rc.1 models the listener holds that version's requests to (the switch window).
SOURCES = ['backend/crosschain_models.py', 'backend/crosschain_models_rc1.py', 'backend/crosschain_service.py',
           'backend/crosschain_api.py', 'backend/crosschain_common.py', 'backend/crosschain_relay.py',
           'backend/crosschain_across.py', 'backend/crosschain_http.py', 'backend/crosschain_config.py',
           'backend/crosschain_pins.json',
           'backend/authenticated_api.py', 'backend/onboarding_auth.py',
           'backend/tests/crosschain_support.py', 'backend/tests/crosschain_contract_fixtures.py',
           'scripts/export-crosschain-contract.py']
HANDWRITTEN = ['runtime.mjs', '../shared/closed-schema.mjs', 'README.md', 'consumer.test.mjs']


def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def typename(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def types(schemas):
    definitions, roots = {}, []

    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        for keyword in ('oneOf', 'anyOf'):
            if keyword in schema:
                return ' | '.join(render(value) for value in schema[keyword])
        if schema.get('type') == 'object':
            required = schema.get('required', [])
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                for key, value in schema['properties'].items()) + '\n}'
        if schema.get('type') == 'array':
            return 'Array<' + render(schema['items']) + '>'
        if schema.get('type') == 'integer' and 'minimum' in schema and schema.get('minimum') == schema.get('maximum'):
            return str(schema['minimum'])
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]

    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_crosschain_type')
                definitions[key] = value
            roots.append(f'export type {typename(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-crosschain-contract.py. No signing authority: unsigned wallet steps only.',
             f'export type CrosschainContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ('Request', 'Response'):
        lines.append('export interface Crosschain' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {typename(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.extend(['export type CrosschainRoute = keyof CrosschainRequests;',
                  'export type CrosschainErrorCode = ' + ' | '.join(json.dumps(code) for code in sorted(ERROR_STATUS_BY_CODE)) + ';',
                  'export type CrosschainError = {error: CrosschainErrorCode};'])
    return '\n\n'.join(lines) + '\n'


def constants():
    """What runtime.mjs needs to re-check a response without the backend: pins, tokens, timings."""
    targets = {}
    for chain, row in sorted(PINS['chains'].items()):
        entry = {'name': row['name']}
        if 'relay' in row:
            entry['relay'] = {'depository': row['relay']['depository']}
        if 'across' in row:
            entry['across'] = {key: row['across'][key] for key in ('spokePool', 'spokePoolPeriphery') if key in row['across']}
        targets[str(chain)] = entry
    return {'appFeeBps': 35, 'quoteLifetimeSeconds': QUOTE_LIFETIME_SECONDS, 'pollSeconds': POLL_SECONDS,
            'destinations': {str(chain): sorted(row['tokens']) for chain, row in sorted(DESTINATIONS.items())},
            'chains': targets}


def build():
    schemas = {}
    files = {}
    for route in sorted(REQUEST_MODELS):
        schemas[route] = {}
        for kind, models in (('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)):
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                           '$id': f'https://domino.invalid/contracts/crosschain-v1/{route}.{kind}.schema.json',
                           'x-contract-version': CONTRACT_VERSION})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object', 'required': ['error'],
        'additionalProperties': False, 'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE})
    requests, responses, errors = build_fixtures()
    for kind, values in (('requests', requests), ('responses', responses)):
        for route, body in values.items():
            files[f'fixtures/{kind}/{route}.json'] = text(body)
    for name, (_route, body) in build_variants().items():
        files[f'fixtures/variants/{name}.json'] = text(body)
    files['fixtures/errors.json'] = text(errors)
    files['schema-data.mjs'] = ('// Generated by scripts/export-crosschain-contract.py.\nexport const SCHEMAS = ' + text(schemas).rstrip()
                                + ';\nexport const ERRORS = ' + text(ERROR_STATUS_BY_CODE).rstrip()
                                + ';\nexport const CONSTANTS = ' + text(constants()).rstrip() + ';\n')
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = '''// Generated by scripts/export-crosschain-contract.py.
import type {CrosschainRoute, CrosschainRequests, CrosschainResponses, CrosschainError, CrosschainErrorCode} from './types.js';
export const CONTRACT_VERSION: '%s';
export const ROUTES: readonly CrosschainRoute[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<CrosschainErrorCode, number>>;
export function validateRequest<R extends CrosschainRoute>(route:R, value:unknown):value is CrosschainRequests[R];
export function validateResponse<R extends CrosschainRoute>(route:R, value:unknown):value is CrosschainResponses[R];
export function validateError(status:number, value:unknown):value is CrosschainError;
/** The tracking rule: [state, transition] for an observation after the state last shown. */
export function advance(previous:string|null, observed:string):[string, string];
''' % CONTRACT_VERSION
    manifest = {'contract': 'crosschain-v1', 'contractVersion': CONTRACT_VERSION,
                'status': 'candidate_disabled_pending_keys_and_worker',
                'generator': 'scripts/export-crosschain-contract.py',
                'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()} for path in SOURCES],
                'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()} for path, value in sorted(files.items())]}
    for path in HANDWRITTEN:
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST / path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name, value in build().items():
        path = DEST / name
        if args.check:
            if not path.is_file() or path.read_text() != value:
                drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    if drift:
        print('Crosschain contract drift: ' + ', '.join(drift))
        return 1
    print('Crosschain contract checked.' if args.check else 'Crosschain contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
