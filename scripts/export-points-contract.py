#!/usr/bin/env python3
"""Export points-v1 (season 1's points for the app): schemas, types, runtime constants and producer fixtures."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'backend'), str(ROOT / 'backend/tests')]
from points_contract_fixtures import build_fixtures  # noqa: E402
from points_models import CONTRACT_VERSION, ERROR_STATUS_BY_CODE, MAX_BODY, MAX_RESPONSE, REQUEST_MODELS, RESPONSE_MODELS  # noqa: E402
from points_referral import SEASON_TITLES  # noqa: E402

DEST = ROOT / 'api-contracts/points-v1'
SOURCES = ['backend/points_models.py', 'backend/points_service.py', 'backend/points_api.py', 'backend/points_referral.py',
           'backend/points_engine.py', 'backend/points_season_1.json', 'backend/migrations/059_points_engine.sql',
           'backend/authenticated_api.py', 'backend/onboarding_auth.py', 'backend/onboarding_models.py',
           'backend/tests/points_contract_fixtures.py', 'scripts/export-points-contract.py']
HANDWRITTEN = ['runtime.mjs', '../shared/closed-schema.mjs', 'README.md', 'consumer.test.mjs']


def text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + '\n'


def typename(route, kind):
    return ''.join(part.title() for part in route.split('-')) + kind.title()


def types(schemas):
    """TypeScript types from the JSON schemas (the crosschain-v1 and position-plan-v1 exporters' renderer)."""
    definitions, roots = {}, []

    def render(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        for keyword in ('oneOf', 'anyOf'):
            if keyword in schema:
                return ' | '.join(render(value) for value in schema[keyword])
        if schema.get('type') == 'object':
            required = schema.get('required', [])
            return '{\n' + '\n'.join('  ' + json.dumps(key) + ('' if key in required else '?') + ': ' + render(value) + ';'
                                     for key, value in schema.get('properties', {}).items()) + '\n}'
        if schema.get('type') == 'array':
            return 'Array<' + render(schema['items']) + '>'
        return {'string': 'string', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}[schema['type']]

    for route, kinds in schemas.items():
        for kind, schema in kinds.items():
            for key, definition in schema.get('$defs', {}).items():
                value = render(definition)
                if key in definitions and definitions[key] != value:
                    raise ValueError('conflicting_points_type')
                definitions[key] = value
            roots.append(f'export type {typename(route, kind)} = {render(schema)};')
    lines = ['// Generated by scripts/export-points-contract.py.',
             f'export type PointsContractVersion = "{CONTRACT_VERSION}";']
    lines.extend(f'export type {key} = {value};' for key, value in sorted(definitions.items()))
    lines.extend(roots)
    for kind in ('Request', 'Response'):
        lines.append('export interface Points' + kind + 's {\n' + '\n'.join(
            f'  "{route}": {typename(route, kind)};' for route in sorted(schemas)) + '\n}')
    lines.extend(['export type PointsRoute = keyof PointsRequests;',
                  'export type PointsErrorCode = ' + ' | '.join(json.dumps(c) for c in sorted(ERROR_STATUS_BY_CODE)) + ';',
                  'export type PointsError = {error: PointsErrorCode};'])
    return '\n\n'.join(lines) + '\n'


def build():
    schemas, files = {}, {}
    for route in sorted(REQUEST_MODELS):
        schemas[route] = {}
        for kind, models in (('request', REQUEST_MODELS), ('response', RESPONSE_MODELS)):
            schema = models[route].model_json_schema()
            schema.update({'$schema': 'https://json-schema.org/draft/2020-12/schema',
                           '$id': f'https://domino.invalid/contracts/points-v1/{route}.{kind}.schema.json',
                           'x-contract-version': CONTRACT_VERSION})
            schemas[route][kind] = schema
            files[f'schemas/{route}.{kind}.schema.json'] = text(schema)
    files['schemas/error.response.schema.json'] = text({
        '$schema': 'https://json-schema.org/draft/2020-12/schema', 'type': 'object', 'required': ['error'],
        'additionalProperties': False, 'properties': {'error': {'type': 'string', 'enum': sorted(ERROR_STATUS_BY_CODE)}},
        'x-status-by-code': ERROR_STATUS_BY_CODE})
    requests, responses, errors, signed_text = build_fixtures()
    for kind, values in (('requests', requests), ('responses', responses)):
        for route, body in values.items():
            files[f'fixtures/{kind}/{route}.json'] = text(body)
    files['fixtures/errors.json'] = text(errors)
    files['fixtures/signed-text.json'] = text(signed_text)
    constants = {'contractVersion': CONTRACT_VERSION, 'maxBody': MAX_BODY, 'maxResponse': MAX_RESPONSE,
                 'seasonTitles': SEASON_TITLES}
    files['schema-data.mjs'] = ('// Generated by scripts/export-points-contract.py.\nexport const SCHEMAS = '
                                + text(schemas).rstrip() + ';\nexport const ERRORS = ' + text(ERROR_STATUS_BY_CODE).rstrip()
                                + ';\nexport const CONSTANTS = ' + text(constants).rstrip() + ';\n')
    files['types.ts'] = types(schemas)
    files['runtime.d.mts'] = '''// Generated by scripts/export-points-contract.py.
import type {PointsRoute, PointsRequests, PointsResponses, PointsError, PointsErrorCode} from './types.js';
export const CONTRACT_VERSION: '%s';
export const ROUTES: readonly PointsRoute[];
export const ERROR_STATUS_BY_CODE: Readonly<Record<PointsErrorCode, number>>;
export const SEASON_TITLES: Readonly<Record<string, string>>;
export function validateRequest<R extends PointsRoute>(route:R, value:unknown):value is PointsRequests[R];
export function validateResponse<R extends PointsRoute>(route:R, value:unknown):value is PointsResponses[R];
export function validateError(status:number, value:unknown):value is PointsError;
/** The exact text a referred wallet signs with personal_sign (backend/points_referral.py message). */
export function referralText(season:string, referee:string, referrer:string, issuedAt:number):string;
''' % CONTRACT_VERSION
    manifest = {'contract': 'points-v1', 'contractVersion': CONTRACT_VERSION,
                'status': 'candidate_disabled_pending_deployment_and_worker',
                'generator': 'scripts/export-points-contract.py',
                'sources': [{'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()} for path in SOURCES],
                'files': [{'path': path, 'sha256': hashlib.sha256(value.encode()).hexdigest()} for path, value in sorted(files.items())]}
    for path in HANDWRITTEN:
        manifest['files'].append({'path': path, 'sha256': hashlib.sha256((DEST / path).read_bytes()).hexdigest()})
    files['manifest.json'] = text(manifest)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for name, value in build().items():
        path = DEST / name
        if args.check:
            if not path.is_file() or path.read_text() != value:
                drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    if drift:
        print('Points contract drift: ' + ', '.join(drift))
        return 1
    print('Points contract checked.' if args.check else 'Points contract exported.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
